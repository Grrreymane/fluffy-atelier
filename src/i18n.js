/* ===== i18n.js — language pick, L() lookup, in-place localisation of the data tables =====
Text is looked up by its Chinese original. I18N_PACK (generated by tools/i18n.cjs into src/lang.js) holds
zh: {key: 中文} and one {key: text} per language; the keys are short hashes of the Chinese text, the same keys
the AIWANNA platform serves at /i18n/<slug>/<lang>.json, so lines the author edits there are layered on top. */
const LANGS = ['zh', 'en', 'ja', 'ko', 'es'];
const PLATFORM_SLUG = 'game-07c6bf44eb23be51';
const LANG = (() => {
  const norm = v => {
    v = String(v || '').toLowerCase();
    if (!v) return '';
    if (v.startsWith('zh')) return 'zh';
    const p = v.split(/[-_]/)[0];
    return LANGS.includes(p) ? p : '';
  };
  let q = '';
  try { q = new URLSearchParams(location.search).get('lang') || ''; } catch (e) { /* no URL */ }
  if (q && norm(q)) return norm(q);
  if (/HeadlessChrome/.test(navigator.userAgent)) return 'zh';
  for (const l of (navigator.languages || [navigator.language])) { const n = norm(l); if (n) return n; }
  return 'en';
})();
const LIST_SEP = { zh: '、', ja: '、' }[LANG] || ', ';
const DICT = {};
function buildDict(over) {
  const zh = I18N_PACK.zh, tr = Object.assign({}, I18N_PACK[LANG] || {}, over || {});
  for (const k in zh) if (tr[k]) DICT[zh[k]] = tr[k];
}
if (LANG !== 'zh') buildDict();
/* L('换上了「{0}」', name): translated text with {0}, {1}… filled in */
function L(s, ...a) {
  const r = (LANG !== 'zh' && DICT[s]) || s;
  return a.length ? r.replace(/\{(\d+)\}/g, (m, i) => (a[i] !== undefined ? a[i] : m)) : r;
}
/* translate a field in place, remembering the original so it can be redone after the platform overlay */
const ZH = new WeakMap();
function trField(o, f) {
  if (!o || typeof o[f] !== 'string') return;
  let z = ZH.get(o); if (!z) ZH.set(o, z = {});
  if (!(f in z)) z[f] = o[f];
  o[f] = L(z[f]);
}
function trDeep(v, fields) {
  if (Array.isArray(v)) { v.forEach(x => trDeep(x, fields)); return; }
  if (!v || typeof v !== 'object') return;
  for (const f of fields) trField(v, f);
}
function trValues(o) { for (const k in o) trField(o, k); }
/* the static page: text nodes, title and aria-label */
const ZH_NODES = new WeakMap();
function trPage() {
  document.documentElement.lang = { zh: 'zh-CN', en: 'en', ja: 'ja', ko: 'ko', es: 'es' }[LANG];
  if (!ZH_NODES.has(document)) ZH_NODES.set(document, document.title);
  document.title = L(ZH_NODES.get(document));
  const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let n = w.nextNode(); n; n = w.nextNode()) {
    const t = n.nodeValue.trim(); if (!t) continue;
    if (!ZH_NODES.has(n)) ZH_NODES.set(n, t);
    n.nodeValue = L(ZH_NODES.get(n));
  }
  for (const el of document.querySelectorAll('[title],[aria-label]')) {
    let z = ZH_NODES.get(el); if (!z) ZH_NODES.set(el, z = { title: el.getAttribute('title'), aria: el.getAttribute('aria-label') });
    if (z.title) el.setAttribute('title', L(z.title));
    if (z.aria) el.setAttribute('aria-label', L(z.aria));
  }
}
/* lines the author edited on AIWANNA; only when the network allows, never blocks the game */
function loadPlatformText(done) {
  if (LANG === 'zh' || !window.fetch) return;
  const ctl = window.AbortController ? new AbortController() : null;
  const tm = setTimeout(() => ctl && ctl.abort(), 8000);
  fetch(`https://www.aiwanna.games/i18n/${PLATFORM_SLUG}/${LANG}.json`, ctl ? { signal: ctl.signal } : {})
    .then(r => (r.ok ? r.json() : null))
    .then(j => {
      clearTimeout(tm);
      if (!j || typeof j !== 'object') return;
      const over = {};
      for (const k in j) if (typeof j[k] === 'string' && j[k] && k in I18N_PACK.zh) over[k] = j[k];
      if (!Object.keys(over).length) return;
      buildDict(over); done();
    })
    .catch(() => clearTimeout(tm));
}
