// node tools/i18n.cjs        -> i18n/zh.json + zh.limits.json from the sources, then src/lang.js from i18n/*.json
// node tools/i18n.cjs check  -> also list keys missing in each translation
// Player-facing Chinese is found as: L('…') arguments, `prop: '…'` data fields (name, n, sub, desc, tag / default
// names), hairDef / backDef / sceneDef names, and the text / title / aria-label of src/template.html.
// Keys are t.<8 hex of sha1(text)>, so a changed line gets a new key and old translations simply drop out.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..'), SRC = path.join(ROOT, 'src'), OUT = path.join(ROOT, 'i18n');
const HAN = /\p{sc=Han}/u;
const LANGS = ['en', 'ja', 'ko', 'es'];
const TITLE = { zh: '绒绒时装屋' };
const key = t => 't.' + crypto.createHash('sha1').update(t).digest('hex').slice(0, 8);
const width = t => [...t].reduce((a, c) => a + (/[ᄀ-ᇿ⺀-꓏가-힯豈-﫿＀-｠　-〿]/.test(c) ? 2 : 1), 0);

const found = [];
const add = t => { if (HAN.test(t) && !found.includes(t)) found.push(t); };
const strip = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1');
const order = ['template.html', 'ui.js', 'species.js', 'body.js', 'face.js', 'hair.js', 'scenes.js', 'defs.js'];
const files = fs.readdirSync(SRC).filter(f => /\.(js|html)$/.test(f) && f !== 'lang.js' && f !== 'i18n.js')
  .sort((a, b) => ((order.indexOf(a) + 1 || 99) - (order.indexOf(b) + 1 || 99)) || a.localeCompare(b));
for (const f of files) {
  let s = fs.readFileSync(path.join(SRC, f), 'utf8');
  if (f.endsWith('.html')) {
    s = s.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<!--[\s\S]*?-->/g, '');
    for (const m of s.matchAll(/(?:title|aria-label)="([^"]+)"/g)) add(m[1].trim());
    for (const m of s.matchAll(/>([^<>]+)</g)) add(m[1].trim());
    continue;
  }
  s = strip(s);
  for (const m of s.matchAll(/\bL\('((?:[^'\\]|\\.)*)'/g)) add(m[1]);
  for (const m of s.matchAll(/\b\w+: *'((?:[^'\\]|\\.)*)'/g)) add(m[1]);
  for (const m of s.matchAll(/\b(?:hairDef|backDef|sceneDef)\('\w+', *'((?:[^'\\]|\\.)*)'/g)) add(m[1]);
}
// the old-save check in load() ('团团') is not shown to players
const SKIP = new Set(['团团']);
const zh = { 'meta.title': TITLE.zh }, limits = { 'meta.title': 40, '*': 120 };
for (const t of found) {
  if (SKIP.has(t)) continue;
  const k = key(t); zh[k] = t;
  const w = width(t);
  limits[k] = w <= 4 ? 16 : w <= 12 ? Math.max(20, Math.round(w * 3.2)) : Math.round(w * 2.8);
}
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'zh.json'), JSON.stringify(zh, null, 1) + '\n');
fs.writeFileSync(path.join(OUT, 'zh.limits.json'), JSON.stringify(limits, null, 1) + '\n');
console.log('zh.json', Object.keys(zh).length, 'lines');

const pack = { zh };
for (const l of LANGS) {
  const f = path.join(OUT, l + '.json');
  if (!fs.existsSync(f)) { console.log(l, 'missing'); continue; }
  const j = JSON.parse(fs.readFileSync(f, 'utf8')), o = {};
  const miss = [];
  for (const k in zh) { if (typeof j[k] === 'string' && j[k]) o[k] = j[k]; else miss.push(k); }
  pack[l] = o;
  console.log(l, Object.keys(o).length + '/' + Object.keys(zh).length, miss.length ? 'missing ' + miss.length : '');
  if (process.argv[2] === 'check') for (const k of miss) console.log('  ', k, zh[k]);
}
fs.writeFileSync(path.join(SRC, 'lang.js'), '/* generated by tools/i18n.cjs from i18n/*.json — do not edit */\nconst I18N_PACK = ' + JSON.stringify(pack) + ';\n');
