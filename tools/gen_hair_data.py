# Build src/hair_data.js from the traced hairstyles.
# usage: gen_hair_data.py '{"style": "trace json path", ...}'
# Each entry: { outer: [closed polys], shadows: [closed polys], strands: [closed polys], inks: [closed polys],
#               open: [polylines along which the outline is not drawn] }. Points [x, y] in fox head coordinates.
import json, sys
MAP = json.loads(sys.argv[1])
BACK = json.loads(sys.argv[2]) if len(sys.argv) > 2 else {}
def rnd(v): return round(v * 2) / 2
def pts(P): return [[rnd(p[0]), rnd(p[1])] for p in P]
out = {}
for style, src in MAP.items():
    D = json.load(open(src))
    e = {k: [pts(p) for p in D.get(k, [])] for k in ('outer', 'shadows', 'strands', 'inks', 'open')}
    # the approved 慵懒中分 tracing came from the first tracer: its strand/ink lines are drawn by hand in hair.js
    if D.get('lines') == 'hand' or style == 'curtain': e['strands'], e['inks'] = [], []
    out[style] = {k: v for k, v in e.items() if v}
back = {}
for style, src in BACK.items():
    D = json.load(open(src))
    back[style] = {'outer': [pts(p) for p in D['back']['outer']]}   # back hair: outline only (shaded by a gradient)
txt = json.dumps(out, separators=(',', ':')); txtb = json.dumps(back, separators=(',', ':'))
open(__import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), '..', 'src', 'hair_data.js'), 'w').write(
    '/* ===== hair_data.js — hairstyle shapes traced from the hairstyle reference sheets (fox head coordinates).\n'
    '   Generated by tools/gen_hair_data.py from tools/trace/*.json; edit the tracing, not this file. ===== */\n'
    'const HAIR_TRACE = ' + txt + ';\nconst HAIR_BACK_TRACE = ' + txtb + ';\n')
print({k: {kk: len(vv) for kk, vv in v.items()} for k, v in out.items()}, 'bytes', len(txt))
print({k: len(v['outer']) for k, v in back.items()}, 'back bytes', len(txtb))
